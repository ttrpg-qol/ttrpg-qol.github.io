export function getSourceName(code) {
  return sourceNames[code] ?? code;
}

export function getSourceLabel(code) {
  const name = getSourceName(code);
  return name === code ? code : `${name} (${code})`;
}

export function matchesSourceSearch(code, query) {
  const normalizedQuery = String(query ?? "").trim().toLocaleLowerCase();
  return !normalizedQuery || `${getSourceName(code)} ${code}`.toLocaleLowerCase().includes(normalizedQuery);
}
